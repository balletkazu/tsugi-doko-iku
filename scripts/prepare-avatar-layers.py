#!/usr/bin/env python3
"""Separate the atelier's painted face marks from the reusable, shaded head.

Run with Python, Pillow and NumPy. The hand-measured coordinates refer to
the 128 px cells prepared by pack-atelier.py. Source atlases stay unmodified.
"""
from pathlib import Path
import json

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1] / "public"
ART = ROOT / "assets" / "atelier"
FRONT = [
    (52, 82, 83, 94), (49, 82, 80, 92), (50, 79, 72, 83), (49, 79, 83, 95),
    (52, 84, 79, 92), (51, 79, 80, 90), (50, 82, 81, 93), (50, 79, 77, 89),
    (52, 84, 72, 85), (56, 82, 63, 74), (53, 78, 63, 74), (50, 78, 68, 80),
    (54, 81, 72, 84), (52, 82, 83, 95), (50, 79, 77, 89), (49, 80, 83, 96),
]
PROFILE = [
    (95, 78, 102, 91), (97, 78, 105, 92), (89, 69, 96, 82), (91, 79, 98, 92),
    (97, 74, 105, 89), (89, 78, 96, 88), (95, 80, 104, 93), (94, 75, 103, 87),
    (96, 70, 102, 83), (92, 61, 98, 74), (90, 60, 96, 73), (90, 62, 98, 76),
    (94, 69, 102, 81), (96, 82, 104, 95), (98, 72, 106, 86), (93, 78, 104, 91),
]
Y, X = np.ogrid[:128, :128]


def cell(sprite, index):
    x, y = index % 4 * 128, index // 4 * 128
    return x, y, sprite.crop((x, y, x + 128, y + 128))


def ellipse(x, y, rx, ry):
    return ((X - x) / rx) ** 2 + ((Y - y) / ry) ** 2 <= 1


def base_and_mask(image, features, side):
    data = np.array(image).astype(float)
    rgb = data[:, :, :3]
    r,g,b = np.moveaxis(rgb, -1, 0)
    if side:
        ex, ey, mx, my = features
        skin_zone = ellipse(ex - 4, ey + 2, 27, 31)
        marks = ellipse(ex, ey, 5, 8) | ellipse(mx, my, 3.8, 3.1)
    else:
        left, right, ey, my = features
        middle = (left + right) / 2
        skin_zone = ellipse(middle, ey + 2, (right-left)/2+19, 30)
        marks = (ellipse(left, ey, 5.7, 7.4) | ellipse(right, ey, 5.7, 7.4)
                 | ellipse(middle, my, 8.5, 4) | ellipse(middle, my - 5, 3.2, 3.2))
        # Above the eye, remove dark brow marks only where the paint is skin
        # on each side. This is particularly important around pointed fringes.
        above = ellipse(left, ey-8, 5.5, 2.5) | ellipse(right, ey-8, 5.5, 2.5)
        marks |= above & (r > 142) & (g > 83)
    skin = (r>167) & (g>106) & (r-g<92) & (g-b>3) & (g-b<74) & skin_zone & (data[:,:,3]>100)
    yy, xx = np.nonzero(skin & ~marks)
    colors = rgb[yy,xx].copy()
    for y,x in zip(*np.nonzero(marks & (data[:,:,3]>152))):
        dist = (xx-x)**2 + (yy-y)**2
        nearest = np.argpartition(dist, 7)[:8]
        weights = 1 / (dist[nearest]+2)
        rgb[y,x] = np.average(colors[nearest],axis=0,weights=weights)
    skin |= marks & (data[:,:,3]>150)
    mask = Image.fromarray((skin*255).astype('uint8')).filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(.52))
    rgba = Image.new("RGBA", (128,128), "white")
    rgba.putalpha(mask)
    return Image.fromarray(data.clip(0,255).astype('uint8')), rgba


def bounds(name, count):
    sheet = Image.open(ART / f"{name}.webp").convert("RGBA")
    return [cell(sheet, i)[2].getchannel("A").point(lambda p: 255 if p > 170 else 0).getbbox() for i in range(count)]


def main():
    neutral = Image.new("RGBA", (512,1024))
    mask = Image.new("RGBA", neutral.size)
    for row, name, points in [(0,'heads',FRONT),(512,'heads-profile',PROFILE)]:
        sheet = Image.open(ART / f"{name}.webp").convert("RGBA")
        for i, features in enumerate(points):
            x,y,head = cell(sheet,i)
            face, zone = base_and_mask(head,features,row>0)
            neutral.paste(face,(x,y+row))
            mask.paste(zone,(x,y+row))
    neutral.save(ART/'neutral-heads.webp',quality=92,method=6)
    mask.save(ART/'skin-zones.webp',lossless=True,method=6)
    data = dict(front=FRONT, profile=PROFILE, rear=bounds('heads-back',16),
                garment=bounds('garments',8), detail=bounds('details',16),
                furniture=bounds('furnishings',16), souvenir=bounds('relics',8))
    lines = ['// Measured source landmarks and opaque bounds. Generated by scripts/prepare-avatar-layers.py.']
    lines += [f'export const {name} = {json.dumps(value,separators=(",",":"))};' for name,value in data.items()]
    (ROOT/'sprite-guides.js').write_text('\n'.join(lines)+'\n')


if __name__ == "__main__":
    main()
